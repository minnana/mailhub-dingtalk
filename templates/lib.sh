#!/usr/bin/env bash
# Shared library: runtime is deliberately fixed to a root-only directory.
set -Eeuo pipefail
umask 077
readonly MAILHUB_ROOT=/opt/mailhub
readonly MAILHUB_RUNTIME=/opt/mailhub/runtime
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
need_root() { [[ $EUID -eq 0 ]] || die 'Run this script with sudo.'; }
load_runtime() {
  need_root
  [[ -f "$MAILHUB_RUNTIME/.mailhub-managed" && -f "$MAILHUB_RUNTIME/.env" ]] || die 'Run bootstrap.sh first.'
  [[ $(stat -c %u "$MAILHUB_RUNTIME/.env") == 0 ]] || die '.env must be owned by root.'
  python3 "$MAILHUB_ROOT/templates/runtime_config.py" check-env "$MAILHUB_RUNTIME/.env"
  # Generated by bootstrap with validated input, never taken from a user upload.
  set -a
  source "$MAILHUB_RUNTIME/.env"
  set +a
  cd "$MAILHUB_ROOT"
}
dc() { docker compose --project-name mailhub --project-directory "$MAILHUB_ROOT" --env-file "$MAILHUB_RUNTIME/.env" -f "$MAILHUB_ROOT/compose.yaml" "$@"; }
ensure_images() {
  local service image_ref
  for service in "$@"; do
    case "$service" in
      app|cron) image_ref=$NEXTCLOUD_IMAGE ;;
      db) image_ref=$MARIADB_IMAGE ;;
      redis) image_ref=$REDIS_IMAGE ;;
      nginx) image_ref=$NGINX_IMAGE ;;
      acme) image_ref=$ACME_IMAGE ;;
      *) die "Unknown image service: $service" ;;
    esac
    [[ $image_ref =~ @sha256:[a-f0-9]{64}$ ]] || die "Service $service is not digest-pinned."
    if docker image inspect "$image_ref" >/dev/null 2>&1; then
      printf 'Using locally cached pinned image for %s.\n' "$service"
    else
      printf 'Downloading missing pinned image for %s.\n' "$service"
      dc pull --quiet "$service"
      docker image inspect "$image_ref" >/dev/null || die "Pinned image is unavailable after pulling $service."
    fi
  done
}
lock_runtime() {
  exec 9>/run/lock/mailhub-maintenance.lock
  flock -n 9 || die 'Another Mailhub operation is running.'
}
drain_cron() {
  python3 "$MAILHUB_ROOT/scripts/drain-cron.py" --timeout 900
}
